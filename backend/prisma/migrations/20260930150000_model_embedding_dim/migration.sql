-- models —— 新增 embedding_dim：向量模型专属的「维度」
--
-- 背景（用户 2026-09-30）：向量模型没有"上下文长度（token）/ 图片 / 思考"这些对话侧概念，
--   它唯一有意义的属性是**维度**。故：
--     · 建/改**向量模型**时向上游**探测**其输出维度，写入本列；
--     · 建知识库时直接**复制**该维度（不再每次建库都探测一次），仍保留探测作为兜底。
--   `maxContext` / `supports_vision` / `supports_reasoning` 对向量模型恒为空/假（前端也不再显示）。
-- ═══════════════════════════════════════════════════════════════════════════

ALTER TABLE "models" ADD COLUMN "embedding_dim" INTEGER;
