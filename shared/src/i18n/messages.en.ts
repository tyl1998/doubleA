/**
 * 界面语言的**英文字典**（P1-23）
 *
 * ## 与 `messages.zh.ts` 的关系（本方案的机制所在）
 *
 * 类型 `Record<MessageKey, string>` 是**故意**的：`MessageKey` 从 zh 推出 ⇒
 * - 这里**少一个** key ⇒ `tsc` 报 `Property 'xxx' is missing`；
 * - 这里**多一个** key（zh 里没有）⇒ `tsc` 报 `Object literal may only specify known properties`。
 *
 * 也就是说"漏译 / 错拼 key"**不可能悄悄通过编译** —— 这正是 `pnpm typecheck` 能当验收用的原因
 * （见 `子方案/界面语言切换.md` §五）。
 *
 * ## 翻译口径
 *
 * - **专有名词不译**：`MCP`、`Provider`（后端概念）、`Key`（厂商后台里的名字）；
 *   产品的品牌词 `doubuleA` 原样。
 * - **"智能体"统一译 `Agent`**（`03` §七 文案词表的英文对应；中文侧仍统一写"智能体"）。
 * - **`{name}` 占位符原样保留**（名字与位置都要一致，否则插值后语序错乱 —— 由 `verify-i18n` 逐条核对）。
 * - 术语与被限定的上下文（如"公开资产引用到私有资产"）宁可长一点，也不为了短而丢语义。
 */

