/**
 * 界面语言的**中文字典**（P1-23）—— 本文件是 key 全集真相
 *
 * ## 为什么这个文件是"真相来源"
 *
 * `MessageKey` 从本文件推出（`keyof typeof zh`），而 `messages.en.ts` 声明为
 * `Record<MessageKey, string>` ⇒ **en 漏一个 key、或多一个 key，`tsc` 立刻报错**。
 * 这是本方案选"自研 typed 运行时"而不是引 i18next / react-intl 的**核心理由**：
 * 那些库的 key 是普通字符串，漏译要到**运行时**才炸 —— 而"错了不会报错"是本仓
 * 最忌讳的一类缺陷（对照 `06` §六 纪律 8/28 的口径）。
 *
 * ## 命名与组织
 *
 * - key 用**点分命名空间**：`<域>.<对象>.<语义>`（如 `nav.agents`、`shell.crumbHome`）；
 * - 域一览：`common`（通用词）/ `nav`（导航与面包屑）/ `shell`（外壳浮层）/ `rail`（会话栏）/
 *   `user`（头像菜单）/ `notice`（403/404 等整页）/ `error`（错误码兜底）/ `label`（`shared`
 *   存量 `*_LABELS` 表的前端覆盖，逐表迁移用）。
 * - **只放"界面文案"**：日志、给 LLM 的工具描述、OpenAPI 注释**不进这里**（`子方案/界面语言切换.md` §3.5）。
 *
 * ## 占位符
 *
 * `{name}` 形式（与"通知模板"的 `{{task}}` 刻意区分）。缺参数时**原样保留**占位符
 * （不抛错、不静默吞），见 `translate()`。
 *
 * ## 施工纪律（后续分批批也要守）
 *
 * 本批只覆盖**公共外壳层**；新增 key 一律**先加这里、再加 `messages.en.ts`**
 * （顺序反了会编译不过 —— 这正是想要的方向）。
 */

